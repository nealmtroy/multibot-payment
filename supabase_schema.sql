-- 1. Tabel Master Bot (Multi-Bot Registry)
CREATE TABLE IF NOT EXISTS public.vip_bots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_code TEXT NOT NULL UNIQUE,
    bot_token TEXT NOT NULL UNIQUE,
    bot_username TEXT NOT NULL DEFAULT '',
    bot_name TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'stopped')),
    sociabuzz_username TEXT DEFAULT NULL,
    sociabuzz_cookie TEXT DEFAULT NULL,
    log_chat_id BIGINT DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_vip_bots_status ON public.vip_bots (status);
ALTER TABLE public.vip_bots ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.vip_bots FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.vip_bots TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.vip_bots_id_seq TO service_role;

-- 2. Tabel Payments (Transaksi & Invoice)
CREATE TABLE IF NOT EXISTS public.vip_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_code TEXT NOT NULL DEFAULT 'default',
    user_id BIGINT NOT NULL,
    username TEXT NOT NULL DEFAULT '',
    full_name TEXT NOT NULL DEFAULT '',
    package_code TEXT NOT NULL DEFAULT '',
    package_name TEXT NOT NULL DEFAULT '',
    package_amount INTEGER NOT NULL DEFAULT 0,
    vip_chat_id BIGINT,
    invite_expire_hours INTEGER NOT NULL DEFAULT 0,
    public_invoice_id TEXT NOT NULL,
    order_id TEXT NOT NULL UNIQUE,
    payment_url TEXT NOT NULL,
    inv_id TEXT NOT NULL UNIQUE,
    amount INTEGER NOT NULL,
    status TEXT NOT NULL CHECK (
        status IN (
            'pending',
            'processing_paid',
            'invite_error',
            'processing_delivery',
            'delivery_error',
            'delivery_blocked',
            'paid',
            'failed_or_expired',
            'unknown',
            'poll_error',
            'timeout'
        )
    ),
    buyer_name TEXT NOT NULL,
    buyer_email TEXT NOT NULL,
    qris_amount TEXT NOT NULL DEFAULT '',
    qris_expires TEXT NOT NULL DEFAULT '',
    qris_chat_id BIGINT,
    qris_message_id BIGINT,
    next_check_at TIMESTAMPTZ,
    poll_attempts INTEGER NOT NULL DEFAULT 0,
    last_polled_at TIMESTAMPTZ,
    invite_link TEXT,
    invite_expires_at TIMESTAMPTZ,
    error TEXT NOT NULL DEFAULT '',
    referral_id BIGINT,
    referrer_user_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

