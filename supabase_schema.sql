-- 9. RPC Functions (dengan parameter p_bot_code)

CREATE OR REPLACE FUNCTION public.vip_increment_pending_referral(p_user_id BIGINT, p_bot_code TEXT DEFAULT 'default')
RETURNS VOID
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS 
    UPDATE public.vip_users
    SET pending_referrals = pending_referrals + 1,
        updated_at = now()
    WHERE user_id = p_user_id AND bot_code = p_bot_code;
;

CREATE OR REPLACE FUNCTION public.vip_credit_referral_commission(p_user_id BIGINT, p_amount INTEGER, p_bot_code TEXT DEFAULT 'default')
RETURNS VOID
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS 
    UPDATE public.vip_users
    SET balance = balance + GREATEST(p_amount, 0),
        pending_referrals = GREATEST(pending_referrals - 1, 0),
        successful_referrals = successful_referrals + 1,
        updated_at = now()
    WHERE user_id = p_user_id AND bot_code = p_bot_code;
;

CREATE OR REPLACE FUNCTION public.vip_credit_balance(p_user_id BIGINT, p_amount INTEGER, p_bot_code TEXT DEFAULT 'default')
RETURNS VOID
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS 
    UPDATE public.vip_users
    SET balance = balance + GREATEST(p_amount, 0),
        updated_at = now()
    WHERE user_id = p_user_id AND bot_code = p_bot_code;
;

CREATE OR REPLACE FUNCTION public.vip_create_withdrawal(
    p_user_id BIGINT,
    p_username TEXT,
    p_full_name TEXT,
    p_amount INTEGER,
    p_phone TEXT,
    p_wallet_name TEXT,
    p_account_name TEXT,
    p_bot_code TEXT DEFAULT 'default'
)
RETURNS SETOF public.vip_withdrawals
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS 
DECLARE
    created public.vip_withdrawals;
BEGIN
    IF p_amount < 10000 THEN
        RETURN;
    END IF;

    UPDATE public.vip_users
    SET balance = balance - p_amount,
        phone = p_phone,
        updated_at = now()
    WHERE user_id = p_user_id
      AND bot_code = p_bot_code
      AND balance >= p_amount;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    INSERT INTO public.vip_withdrawals (
        bot_code,
        user_id,
        username,
        full_name,
        amount,
        phone,
        wallet_name,
        account_name,
        status,
        created_at,
        updated_at
    ) VALUES (
        p_bot_code,
        p_user_id,
        p_username,
        p_full_name,
        p_amount,
        p_phone,
        p_wallet_name,
        p_account_name,
        'pending',
        now(),
        now()
    ) RETURNING * INTO created;

    RETURN NEXT created;
END;
;

